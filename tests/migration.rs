use digest::OutputSizeUser;
use hybrid_array::typenum::Unsigned;
use opaque_ke::key_exchange::group::Group;
use opaque_ke::ksf::Identity;
use opaque_ke::{CipherSuite, ClientLogin, ServerLogin, ServerRegistration, ServerSetup, TripleDh};
use p256::NistP256;
use rand::rand_core::UnwrapErr;
use rand::rngs::SysRng;
use sha2::Sha256;

const PASSWORD: &[u8] = b"test password";
const CLIENT_IDENTIFIER: &[u8] = b"test client identifier";

struct NewCipherSuite;

impl CipherSuite for NewCipherSuite {
    type OprfCs = NistP256;
    type KeyExchange = TripleDh<NistP256, Sha256>;
    type Ksf = Identity;
}

/// Migrate public fixtures generated by opaque-ke 3.0.0 without retaining its
/// old crypto dependencies.
#[test]
fn registration_upload() {
    let fixture: serde_json::Value =
        serde_json::from_str(include_str!("fixtures/opaque-ke-3.0.0.json")).unwrap();
    let old_setup = hex::decode(fixture["server_setup"].as_str().unwrap()).unwrap();
    let registration = hex::decode(fixture["registration"].as_str().unwrap()).unwrap();

    // V3 stores the dummy private key; V4 stores its public key instead.
    let prefix_len =
        <Sha256 as OutputSizeUser>::OutputSize::USIZE + <NistP256 as Group>::SkLen::USIZE;
    let (prefix, mut fake_private_key) = old_setup.split_at(prefix_len);
    let fake_private_key = NistP256::deserialize_take_sk(&mut fake_private_key).unwrap();
    let fake_public_key = NistP256::serialize_pk(&NistP256::public_key(&fake_private_key));
    let setup = [prefix, fake_public_key.as_slice()].concat();
    let server_setup = ServerSetup::<NewCipherSuite>::deserialize(&setup).unwrap();
    let registration = ServerRegistration::<NewCipherSuite>::deserialize(&registration).unwrap();

    let mut rng = UnwrapErr(SysRng);
    let client = ClientLogin::<NewCipherSuite>::start(&mut rng, PASSWORD).unwrap();
    let server = ServerLogin::start(
        &mut rng,
        &server_setup,
        Some(registration),
        client.message,
        CLIENT_IDENTIFIER,
        Default::default(),
    )
    .unwrap();
    let client = client
        .state
        .finish(&mut rng, PASSWORD, server.message, Default::default())
        .unwrap();
    let server = server
        .state
        .finish(client.message, Default::default())
        .unwrap();
    assert_eq!(client.session_key, server.session_key);
}
